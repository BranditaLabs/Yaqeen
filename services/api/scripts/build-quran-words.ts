/**
 * Builds services/api/data/quran-words.txt — the compact, normalised word list the AI check aligns a
 * recording against (domain/recitation-match.ts). Generated from the app's bundled mushaf text
 * (apps/mobile/assets/quran/quran.json, itself built verbatim by tools/quran/build_quran.py from its
 * pinned, attributed source), so word indices match the app's `RecitationAligner.words` exactly.
 * Matching keys only (letters, no tashkeel): never shown to anyone.
 *
 *   pnpm --filter @yaqeen/api exec tsx scripts/build-quran-words.ts           # write
 *   pnpm --filter @yaqeen/api exec tsx scripts/build-quran-words.ts --check   # fail on drift
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { normWord, splitWords } from '../src/domain/recitation-match.js';

const src = fileURLToPath(new URL('../../../apps/mobile/assets/quran/quran.json', import.meta.url));
const out = fileURLToPath(new URL('../data/quran-words.txt', import.meta.url));
const q = JSON.parse(readFileSync(src, 'utf8')) as { sources: Record<string, { name: string; version: string; licence: string }>; ayat: string[][] };

const lines = [
  '# Normalised Quran words (matching keys only, one ayah per line in mushaf order: 1:1 … 114:6).',
  '# Generated by services/api/scripts/build-quran-words.ts from apps/mobile/assets/quran/quran.json.',
  `# Text source: ${q.sources.text!.name} ${q.sources.text!.version} — ${q.sources.text!.licence}.`,
  '# Do not edit by hand.',
];
let ayat = 0;
for (const [s, surah] of q.ayat.entries()) {
  for (const [a, text] of surah.entries()) {
    const words = splitWords(text).map(normWord);
    if (words.length === 0 || words.some((w) => w.length === 0)) throw new Error(`empty word in ${s + 1}:${a + 1}`);
    lines.push(words.join(' '));
    ayat++;
  }
}
if (ayat !== 6236) throw new Error(`expected 6236 ayat, got ${ayat}`);
const text = `${lines.join('\n')}\n`;
if (process.argv.includes('--check')) {
  const cur = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  if (cur !== text) {
    console.error('quran-words.txt is out of date: run scripts/build-quran-words.ts');
    process.exit(1);
  }
  console.log('quran-words.txt is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${ayat} ayat, ${Buffer.byteLength(text)} bytes)`);
}

#!/usr/bin/env node
/**
 * Embed the 16 preset avatars into the API (served at /u/assets/avatars/<id>.webp, immutable), so the
 * image needs no asset files — like brand-assets.ts. Source of truth: packages/brand/avatars/avatars.json
 * and the app's WebP art (apps/mobile/assets/avatars/<id>.webp), re-encoded at 256 px.
 *
 *   node services/api/scripts/gen-avatar-assets.mjs           # write src/web/avatar-assets.ts
 *   node services/api/scripts/gen-avatar-assets.mjs --check   # fail when the file is out of date
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..', '..');
const presets = JSON.parse(readFileSync(join(repo, 'packages/brand/avatars/avatars.json'), 'utf8'));
const out = join(here, '..', 'src/web/avatar-assets.ts');

const lines = [
  '/**',
  ' * Preset profile avatars for public pages, embedded so the API image needs no asset files.',
  ' * Generated by services/api/scripts/gen-avatar-assets.mjs from packages/brand/avatars — do not edit by hand.',
  ' */',
  '',
  '/** id → 256-px WebP, base64. */',
  'export const AVATAR_WEBP: Record<string, string> = {',
];
for (const p of presets) {
  const src = join(repo, 'apps/mobile/assets/avatars', `${p.id}.webp`);
  // Deterministic: fixed size, quality and effort; no metadata.
  const buf = await sharp(readFileSync(src)).resize(256, 256, { fit: 'cover' }).webp({ quality: 82, effort: 6 }).toBuffer();
  lines.push(`  ${p.id}: '${buf.toString('base64')}',`);
}
lines.push('};', '', '/** Preset labels (alt text). */');
lines.push(`export const AVATAR_LABELS: Record<string, { ar: string; en: string }> = ${JSON.stringify(Object.fromEntries(presets.map((p) => [p.id, { ar: p.ar, en: p.en }])), null, 2)};`, '');
const text = lines.join('\n');

if (process.argv.includes('--check')) {
  const have = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (have !== text) {
    console.error('src/web/avatar-assets.ts is out of date — run node services/api/scripts/gen-avatar-assets.mjs');
    process.exit(1);
  }
  console.log('avatar assets up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${presets.length} presets)`);
}
// sharp's worker pool can keep the event loop alive on some platforms.
process.exit(0);

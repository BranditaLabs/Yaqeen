#!/usr/bin/env python3
"""Generate services/api/src/domain/city-coords.ts from the app's offline city list.

The API only needs coarse coordinates to keep marketing pushes away from each user's prayer
times; it gets the city name the user picked (never GPS). Run after changing cities.json:
    python3 tools/geo/gen_api_cities.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
src = json.loads((ROOT / 'apps/mobile/assets/geo/cities.json').read_text(encoding='utf-8'))
by_name: dict[str, tuple[float, float]] = {}
by_tz: dict[str, tuple[float, float]] = {}
for name_en, _name_ar, _cc, lat, lng, tz in src['cities']:
    key = f'{name_en}|{tz}'
    by_name.setdefault(key, (round(lat, 2), round(lng, 2)))
    by_tz.setdefault(tz, (round(lat, 2), round(lng, 2)))  # list is ordered by size: first = largest


def entries(d):
    return ',\n'.join(f'  {json.dumps(k, ensure_ascii=False)}: [{v[0]}, {v[1]}]' for k, v in sorted(d.items()))


out = f"""// GENERATED by tools/geo/gen_api_cities.py from apps/mobile/assets/geo/cities.json — do not edit.
/* eslint-disable */
/** "<city name (en)>|<IANA zone>" → [lat, lng] (2 decimals ≈ 1 km — coarse on purpose). */
export const CITY_COORDS: Record<string, [number, number]> = {{
{entries(by_name)},
}};

/** IANA zone → the largest listed city in it (fallback when the user picked no city). */
export const ZONE_COORDS: Record<string, [number, number]> = {{
{entries(by_tz)},
}};
"""
(ROOT / 'services/api/src/domain/city-coords.ts').write_text(out, encoding='utf-8')
print(f'{len(by_name)} cities, {len(by_tz)} zones')

// Generates apps/mobile/test/fixtures/recordings/constants.json from @yaqeen/contracts, so the Dart
// mirrors in lib/features/recordings/domain/recording_models.dart (limits, format, statuses, reasons,
// reactions, error codes) are checked for drift by test/features/recordings_models_test.dart.
//
//   pnpm --filter @yaqeen/contracts build && node tools/contracts/gen_recordings_fixtures.mjs          # write
//   node tools/contracts/gen_recordings_fixtures.mjs --check                                         # fail on drift
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = new URL('../../', import.meta.url);
const c = await import(pathToFileURL(fileURLToPath(new URL('packages/contracts/dist/index.js', root))).href);
const out = fileURLToPath(new URL('apps/mobile/test/fixtures/recordings/constants.json', root));

const data = {
  $comment: 'Generated by tools/contracts/gen_recordings_fixtures.mjs from @yaqeen/contracts. Do not edit by hand.',
  RECORDING_MAX_MS: c.RECORDING_MAX_MS,
  RECORDING_MAX_BYTES: c.RECORDING_MAX_BYTES,
  RECORDING_FORMAT: { ...c.RECORDING_FORMAT, mimes: [...c.RECORDING_FORMAT.mimes] },
  PROFILE_RECORDINGS_MAX: c.PROFILE_RECORDINGS_MAX,
  RECORDING_UPLOADS_PER_DAY: c.RECORDING_UPLOADS_PER_DAY,
  COMMENT_MAX: c.COMMENT_MAX,
  COMMENT_MIN: c.COMMENT_MIN,
  RECORDING_STATUSES: [...c.RECORDING_STATUSES],
  REJECT_REASONS: [...c.REJECT_REASONS],
  RECORDING_VISIBILITIES: [...c.RECORDING_VISIBILITIES],
  REACTION_KINDS: [...c.REACTION_KINDS],
  REACTION_COPY: c.REACTION_COPY,
  RECORDING_REPORT_REASONS: [...c.RECORDING_REPORT_REASONS],
  RECORDING_ERROR_CODES: [...c.RECORDING_ERROR_CODES],
  RECITATION_MATCH: c.RECITATION_MATCH,
};

const text = `${JSON.stringify(data, null, 2)}\n`;
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // missing → drift
  }
  if (current !== text) {
    console.error(`${out} is out of date with @yaqeen/contracts. Run: node tools/contracts/gen_recordings_fixtures.mjs`);
    process.exit(1);
  }
  console.log('recordings constants.json matches @yaqeen/contracts');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}

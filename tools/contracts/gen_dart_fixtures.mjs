// Generates apps/mobile/test/fixtures/community/constants.json from @yaqeen/contracts, so the Dart
// mirrors (DIVISIONS, BADGE_KINDS, COMMUNITY_ERROR_CODES, AVATAR_PRESETS, LEVELS + levelFor vectors,
// EARNED/LEVEL_REASONS) are checked for drift by apps/mobile/test/features/community_models_test.dart.
//
//   pnpm --filter @yaqeen/contracts build && node tools/contracts/gen_dart_fixtures.mjs          # write
//   node tools/contracts/gen_dart_fixtures.mjs --check                                         # fail on drift
//
// `--check` runs as part of `pnpm --filter @yaqeen/contracts test` (and so `pnpm test`).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = new URL('../../', import.meta.url);
const c = await import(pathToFileURL(fileURLToPath(new URL('packages/contracts/dist/index.js', root))).href);
const out = fileURLToPath(new URL('apps/mobile/test/fixtures/community/constants.json', root));

// Boundaries and in-between values for every level, plus a negative.
const samples = [-5, 0, 1, 250, 499, 500, 501, 1250, 1999, 2000, 3500, 4999, 5000, 8500, 11999, 12000, 18500, 24999, 25000, 25001, 100000];

const data = {
  $comment: 'Generated by tools/contracts/gen_dart_fixtures.mjs from @yaqeen/contracts. Do not edit by hand.',
  AVATAR_PRESETS: [...c.AVATAR_PRESETS],
  AVATAR_KINDS: [...c.AVATAR_KINDS],
  DISPLAY_NAME_MAX: c.DISPLAY_NAME_MAX,
  DIVISIONS: c.DIVISIONS.map((d) => ({ ...d })),
  BADGE_KINDS: [...c.BADGE_KINDS],
  COMMUNITY_ERROR_CODES: [...c.COMMUNITY_ERROR_CODES],
  REPORT_REASONS: [...c.REPORT_REASONS],
  EARNED_REASONS: [...c.EARNED_REASONS],
  LEVEL_REASONS: [...c.LEVEL_REASONS],
  K_COUNTRY_BOARD: c.K_COUNTRY_BOARD,
  LEVELS: c.LEVELS.map((l) => ({ ...l })),
  levelFor: samples.map((points) => ({ points, ...c.levelFor(points) })),
};

const text = `${JSON.stringify(data, null, 2)}\n`;
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // missing → drift
  }
  if (current !== text) {
    console.error(`${out} is out of date with @yaqeen/contracts. Run: node tools/contracts/gen_dart_fixtures.mjs`);
    process.exit(1);
  }
  console.log('constants.json matches @yaqeen/contracts');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
